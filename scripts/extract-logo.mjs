// Generates inline logo geometry and cacheable wood-grain overlays from the
// owner-supplied vector artwork in docs/brand/logo. Nothing is redrawn: paths
// are copied as-is, with coordinates rounded to 0.1 units (the viewBox is
// ~2900 units wide, so this is far below one screen pixel).
//
//   node scripts/extract-logo.mjs
//
// Outputs:
//   components/brand/logo-data.ts       silhouette, blue half, veins and letters (hero animation)
//   public/brand/oakteck-logo-sprite.svg the same geometry as a cached sprite for <Logo>
//   public/brand/oakteck-grain-logo.svg wood grain for the full logo (clipped)
//   public/brand/oakteck-grain-mark.svg wood grain for the leaf mark (clipped)
import { readFileSync, writeFileSync } from "node:fs";

const src = (f) => readFileSync(new URL(`../docs/brand/logo/${f}`, import.meta.url), "utf8");
const round = (d) =>
  d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(parseFloat(n) * 10) / 10));
const must = (s, re, what) => {
  const m = s.match(re);
  if (!m) throw new Error(`Could not find ${what}`);
  return m[1];
};
const viewBox = (s) => must(s, /viewBox="([^"]+)"/, "viewBox");

function leafParts(s, clipId) {
  return {
    viewBox: viewBox(s),
    silhouette: round(must(s, new RegExp(`<clipPath id="${clipId}"><path d="([^"]+)"`), "silhouette")),
    blue: round(must(s, /<path d="([^"]+)" fill="#1380CC" fill-rule="evenodd"/, "blue half")),
    veins: round(must(s, /<path d="([^"]+)" fill="#111111" fill-rule="evenodd"/, "veins")),
  };
}

const logoDark = src("oakteck-logo-on-dark.svg");
const mark = src("oakteck-mark.svg");

const wordmark = must(logoDark, /<g id="wordmark">([\s\S]*?)<\/g>/, "wordmark");
const letters = [...wordmark.matchAll(/<path d="([^"]+)" fill="([^"]+)"/g)].map((m) => ({
  d: round(m[1]),
  // OAK is white on dark / navy on light; TECK is brand blue in both.
  part: m[2].toUpperCase() === "#1380CC" ? "teck" : "oak",
}));
if (letters.length !== 7) throw new Error(`Expected 7 letters, found ${letters.length}`);

const logo = leafParts(logoDark, "sil");
const markParts = leafParts(mark, "msil");

const ts = `// Generated by scripts/extract-logo.mjs from docs/brand/logo. Do not edit by hand.
export const LOGO = ${JSON.stringify({ ...logo, letters }, null, 2)} as const;

export const MARK = ${JSON.stringify(markParts, null, 2)} as const;

export const LEAF_COLORS = { wood: "#C69A6D", blue: "#1380CC", veins: "#111111" } as const;
`;
writeFileSync(new URL("../components/brand/logo-data.ts", import.meta.url), ts);

function grainSvg(s, clipId) {
  const vb = viewBox(s);
  const clip = must(s, new RegExp(`<clipPath id="${clipId}"><path d="([^"]+)"`), "clip");
  const grain = must(s, new RegExp(`<g clip-path="url\\(#${clipId}\\)">([\\s\\S]*?)</g>`), "grain");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}"><defs><clipPath id="g"><path d="${round(clip)}"/></clipPath></defs><g clip-path="url(#g)">${round(grain)}</g></svg>\n`;
}
writeFileSync(new URL("../public/brand/oakteck-grain-logo.svg", import.meta.url), grainSvg(logoDark, "sil"));
writeFileSync(new URL("../public/brand/oakteck-grain-mark.svg", import.meta.url), grainSvg(mark, "msil"));

// External sprite for <Logo>: the geometry is fetched once and cached, instead
// of repeating in every page's HTML. Split into base (wood silhouette) and top
// (blue half, veins, letters) so the cached wood-grain overlay sits between them.
const letterPaths = (oakFill) =>
  letters.map((l) => `<path d="${l.d}" fill="${l.part === "teck" ? "#1380CC" : oakFill}"/>`).join("");
const top = (g) => `<path d="${g.blue}" fill="#1380CC" fill-rule="evenodd"/><path d="${g.veins}" fill="#111111" fill-rule="evenodd"/>`;
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">
<symbol id="logo-base" viewBox="${logo.viewBox}"><path d="${logo.silhouette}" fill="#C69A6D"/></symbol>
<symbol id="logo-top-dark" viewBox="${logo.viewBox}">${top(logo)}${letterPaths("#FFFFFF")}</symbol>
<symbol id="logo-top-light" viewBox="${logo.viewBox}">${top(logo)}${letterPaths("#0D1B2A")}</symbol>
<symbol id="mark-base" viewBox="${markParts.viewBox}"><path d="${markParts.silhouette}" fill="#C69A6D"/></symbol>
<symbol id="mark-top" viewBox="${markParts.viewBox}">${top(markParts)}</symbol>
</svg>
`;
writeFileSync(new URL("../public/brand/oakteck-logo-sprite.svg", import.meta.url), sprite);

console.log("Logo data written.");
