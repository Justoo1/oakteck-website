// Copies the brand glyphs the site uses from simple-icons (CC0) into a small
// generated module, so the 5 MB simple-icons index never enters the build.
//   node scripts/extract-icons.mjs
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

const wanted = {
  whatsapp: "siWhatsapp",
  github: "siGithub",
  python: "siPython",
  fastapi: "siFastapi",
  django: "siDjango",
  nextjs: "siNextdotjs",
  react: "siReact",
  typescript: "siTypescript",
  postgresql: "siPostgresql",
  redis: "siRedis",
  docker: "siDocker",
  odoo: "siOdoo",
  langchain: "siLangchain",
};

const out = {};
for (const [key, name] of Object.entries(wanted)) {
  const icon = si[name];
  if (!icon) throw new Error(`simple-icons has no ${name}`);
  out[key] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
}

// One export per icon so client components only bundle the glyphs they import.
const lines = Object.entries(out).map(
  ([key, icon]) => `export const ${key}Icon = ${JSON.stringify(icon)} as const;`,
);
writeFileSync(
  new URL("../components/brand/brand-icons.ts", import.meta.url),
  [
    "// Generated by scripts/extract-icons.mjs from simple-icons (CC0). Do not edit by hand.",
    ...lines,
    "",
    "export type BrandIconData = { readonly title: string; readonly hex: string; readonly path: string };",
    "",
  ].join("\n"),
);
// Sprite for the tech marquee: referenced with <use>, so the paths are fetched
// once and cached instead of being repeated in the page HTML.
const spriteKeys = ["python", "fastapi", "django", "nextjs", "react", "typescript", "postgresql", "redis", "docker", "odoo", "langchain"];
writeFileSync(
  new URL("../public/brand/tech-icons.svg", import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg">${spriteKeys
    .map((k) => `<symbol id="${k}" viewBox="0 0 24 24"><path fill="currentColor" d="${out[k].path}"/></symbol>`)
    .join("")}</svg>\n`,
);

console.log(`Wrote ${Object.keys(out).length} brand icons.`);
