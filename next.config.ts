import type { NextConfig } from "next";
import createMDX from "@next/mdx";

/**
 * Two hosting targets from one codebase (see README → "Hosting"):
 *   - default (Vercel / any Node.js host): `npm run build`
 *   - Cloudflare static export:           `npm run build:cloudflare` (DEPLOY_TARGET=cloudflare)
 */
const isCloudflare = process.env.DEPLOY_TARGET === "cloudflare";

const nextConfig: NextConfig = {
  // Classic static rendering (not Cache Components): every page is prerendered at
  // build time, which also lets the same app build as a static export.
  typedRoutes: true,
  poweredByHeader: false,
  // `.vercel.ts` files (the /api/contact route handler) exist only on the Node.js build;
  // on Cloudflare the Worker in worker/index.ts serves that endpoint.
  pageExtensions: isCloudflare ? ["ts", "tsx", "md", "mdx"] : ["ts", "tsx", "md", "mdx", "vercel.ts"],
  ...(isCloudflare && { output: "export" }),
  images: isCloudflare
    ? {
        // No image server in a static export: widths are pre-generated by scripts/build-images.mjs.
        loader: "custom",
        loaderFile: "./lib/static-image-loader.ts",
        deviceSizes: [640, 828, 1200, 1440],
        imageSizes: [256, 384],
        qualities: [60, 75, 85],
      }
    : {
        formats: ["image/avif", "image/webp"],
        qualities: [60, 75, 85],
      },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  // On Cloudflare, www -> bare domain is a Redirect Rule in the dashboard (README → "Hosting").
  ...(!isCloudflare && {
    async redirects() {
      return [
        {
          // www.oakteckgh.com -> oakteckgh.com (also configure this on the Vercel domain).
          source: "/:path*",
          has: [{ type: "host", value: "www.oakteckgh.com" }],
          destination: "https://oakteckgh.com/:path*",
          permanent: true,
        },
      ];
    },
  }),
};

const withMDX = createMDX({});

export default withMDX(nextConfig);
